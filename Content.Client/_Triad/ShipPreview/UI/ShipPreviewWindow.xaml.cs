using Content.Shared._NF.Shipyard.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Triad.ShipPreview.UI;

[GenerateTypedNameReferences]
public sealed partial class ShipPreviewWindow : DefaultWindow
{
    private VesselPrototype? _vessel;

    public ShipPreviewWindow()
    {
        RobustXamlLoader.Load(this);

        ShipView.ShipChanged += RefreshLabels;
        ResetViewButton.OnPressed += _ => ShipView.FitShipToView();
        OnClose += ReleasePreview;

        RefreshLabels();
    }

    public static ShipPreviewWindow OpenFor(VesselPrototype vessel)
    {
        var window = new ShipPreviewWindow();
        window.ShowVessel(vessel);
        window.OpenCentered();
        return window;
    }

    public void ShowVessel(VesselPrototype vessel)
    {
        _vessel = vessel;
        ShipView.ShowVessel(vessel);
        RefreshLabels();
    }

    private void ReleasePreview()
    {
        ShipView.ShipChanged -= RefreshLabels;
        ShipView.CloseScene();
    }

    private void RefreshLabels()
    {
        VesselNameLabel.Text = _vessel?.Name ?? Loc.GetString("triad-ship-preview-no-vessel");
        ShipSizeLabel.Text = ShipView.HasShip ? DescribeShipSize() : string.Empty;
    }

    private string DescribeShipSize()
    {
        return Loc.GetString("triad-ship-preview-info",
            ("width", ShipView.ShipSizeInTiles.X),
            ("height", ShipView.ShipSizeInTiles.Y),
            ("count", ShipView.ShipTileCount));
    }
}
