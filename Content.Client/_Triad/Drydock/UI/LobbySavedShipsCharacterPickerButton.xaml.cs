using Content.Client.Lobby;
using Content.Shared.Humanoid;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;

namespace Content.Client._Triad.Drydock.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbySavedShipsCharacterPickerButton : ContainerButton
{
    private IEntityManager _entManager;

    private EntityUid _previewDummy;

    public LobbySavedShipsCharacterPickerButton(
        IEntityManager entityManager,
        IPrototypeManager prototypeManager,
        ICharacterProfile profile)
    {
        RobustXamlLoader.Load(this);
        _entManager = entityManager;
        AddStyleClass(StyleClassButton);

        if (profile is not HumanoidCharacterProfile humanoid)
        {
            _previewDummy = entityManager.SpawnEntity(prototypeManager.Index(SharedHumanoidAppearanceSystem.DefaultSpecies).DollPrototype, MapCoordinates.Nullspace);
        }
        else
        {
            _previewDummy = UserInterfaceManager.GetUIController<LobbyUIController>()
                .LoadProfileEntity(humanoid, null, true);
        }

        NameLabel.Text = profile.Name;
        View.SetEntity(_previewDummy);
    }

    public void ClearPreview()
    {
        _entManager.DeleteEntity(_previewDummy);
        _previewDummy = EntityUid.Invalid;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        ClearPreview();
    }
}
