using System.ComponentModel;
using Content.Client._Triad.Shipyard.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Shipyard.BUI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Triad.Drydock.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbySavedShipsWindow : FancyWindow
{
    [Dependency] private IEntitySystemManager _entitySystem = default!;

    public event Action? RequestBerthInfo;

    public LobbySavedShipsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateUi(List<DrydockBerthInfo> berths)
    {
        foreach (var berth in berths)
        {
            if (berth.OccupantShipId == null)
                continue;

            var newBerthRow = new DrydockBerthRow(berth, false, selectable: true);
            ShipInfoContainer.AddChild(newBerthRow);
        }

        var hasAvailableShip = berths.Count > 0;
        NoShipsContainer.Visible = !hasAvailableShip;
        InfoContentContainer.Visible = hasAvailableShip;
    }

    public new void OpenCentered()
    {
        base.OpenCentered();
        RequestBerthInfo?.Invoke();
    }
}
