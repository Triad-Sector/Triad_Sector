namespace Content.Client._Triad.Drydock.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbySavedShipsWindow : FancyWindow
{
    [Dependency] private IClientPreferencesManager _prefManager = default!;
    [Dependency] private IStateManager _state = default!;
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private const float ExportTimeoutSeconds = 10f;

    private DrydockBerthInfo? _selectedBerth;
    private readonly List<BaseWindow> _openWindows = new();
    private readonly List<DrydockBerthRow> _berthRows = new();
    private readonly Dictionary<int, LobbySavedShipsCharacterPickerButton> _characterButtons = new();

    private bool _transferMode;

    private float? _exportElapsed;

    private bool _exportReplied;

    public event Action<Guid, string>? OnDeleteShip;
    public event Action<Guid>? OnExportShip;
    public event Action<Guid, int>? OnTransferShip;

    public bool Exporting => _exportElapsed != null;

    public LobbySavedShipsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // 5:3:4.
        OuterSplit.SetSplitFractionOnNextArrange(5f / 12f);
        InnerSplit.SetSplitFractionOnNextArrange(3f / 7f);

        BuildCharacters();
        RefreshCharacters();

        _state.OnStateChanged += OnStateChanged;
    }

    public void UpdateUi(List<DrydockBerthInfo> berths)
    {
        _berthRows.Clear();
        ShipInfoContainer.RemoveAllChildren();

        var shown = new List<DrydockBerthInfo>();
        foreach (var berth in berths)
        {
            if (berth.OccupantShipId == null)
                continue;

            shown.Add(berth);
            var newRow = new DrydockBerthRow(berth, false, selectable: true);

            var pick = new ContainerButton { HorizontalExpand = true };
            pick.AddChild(newRow);
            pick.OnMouseEntered += _ => newRow.SetHovered(true);
            pick.OnMouseExited += _ => newRow.SetHovered(false);
            pick.OnPressed += _ => SelectBerth(berth);

            _berthRows.Add(newRow);
            ShipInfoContainer.AddChild(pick);
        }

        var hasAvailableShip = shown.Count > 0;
        NoShipsContainer.Visible = !hasAvailableShip;
        OuterSplit.Visible = hasAvailableShip;

        SelectBerth(shown.Find(b => b.OccupantShipId == _selectedBerth?.OccupantShipId));
    }

    private void SelectBerth(DrydockBerthInfo? berth)
    {
        if (berth?.OccupantShipId != _selectedBerth?.OccupantShipId)
            _transferMode = false;

        _selectedBerth = berth;

        foreach (var row in _berthRows)
            row.SetSelected(row.BerthId == berth?.BerthId);

        PopulateBerthDetail();
        RefreshCharacters();
    }

    private void PopulateBerthDetail()
    {
        BerthDetailPlaceholder.Visible = _selectedBerth == null;
        BerthDetail.Visible = _selectedBerth != null;
        BerthDetailLines.RemoveAllChildren();
        BerthActions.RemoveAllChildren();

        if (_selectedBerth is not { } berth)
            return;

        var title = new FormattedMessage();
        title.AddBoldSized(berth.OccupantName ?? Loc.GetString("shipyard-console-detail-empty-title", ("berth", berth.BerthId)), 14);
        BerthDetailTitle.SetMessage(title);

        TryGetCharacterName(berth.OccupantCharacterIndex, out var ownedCharName);
        var status = new FormattedMessage();
        status.AddMarkupPermissive(Loc.GetString("shipyard-console-detail-owned-character", ("character", ownedCharName)));
        if (berth.OccupantState == "Impounded")
        {
            status.AddText(" · ");
            status.PushColor(DrydockText.Impound);
            status.AddText(Loc.GetString("shipyard-console-impound-tag"));
            status.Pop();
        }
        BerthDetailStatus.SetMessage(status);

        BerthDetailLines.AddChild(DrydockText.CardLine("shipyard-console-detail-berth-class", DrydockText.Class(berth.MaxSizeClass), null));
        BerthDetailLines.AddChild(DrydockText.CardLine("shipyard-console-detail-ship-class", DrydockText.Class(berth.OccupantSizeClass), null));
        if (berth.OccupantAppraisal is { } appraisal)
            BerthDetailLines.AddChild(DrydockText.CardLine("shipyard-console-detail-appraisal", BankSystemExtensions.ToSpesoString(appraisal), null));

        foreach (var item in ShipVerbs(berth))
            BerthActions.AddChild(ShipyardConsoleMenu.BerthActionButton(item));
    }

    private List<DrydockMenuButton.Item> ShipVerbs(DrydockBerthInfo berth)
    {
        var items = new List<DrydockMenuButton.Item>();

        if (berth.OccupantShipId is not { } occupant || berth.OccupantState != "Stored")
            return items;

        var shipName = berth.OccupantName ?? "?";
        var canTransfer = TransferTargets(berth.OccupantCharacterIndex) > 0;

        items.Add(new DrydockMenuButton.Item(
            Loc.GetString(_transferMode ? "shipyard-console-saved-ships-transfer-cancel" : "shipyard-console-menu-transfer-owner"),
            null,
            canTransfer,
            ToggleTransferMode,
            false,
            Loc.GetString(canTransfer ? "shipyard-console-detail-transfer-owner" : "shipyard-console-saved-ships-transfer-only-one")));

        items.Add(new DrydockMenuButton.Item(
            Loc.GetString(Exporting ? "shipyard-console-exporting" : "shipyard-console-export-button"),
            null,
            !Exporting,
            () => TryExport(occupant),
            false,
            Loc.GetString("shipyard-console-export-detail")));

        items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-delete-ship"),
            null,
            true,
            () => OpenDeletePrompt(occupant, shipName, berth.BerthId),
            false,
            Loc.GetString("shipyard-console-detail-delete-ship")));

        return items;
    }

    private void ToggleTransferMode()
    {
        _transferMode = !_transferMode;
        PopulateBerthDetail();
        RefreshCharacters();
    }


    private void BuildCharacters()
    {
        Characters.RemoveAllChildren();
        _characterButtons.Clear();

        if (!_prefManager.ServerDataLoaded || _prefManager.Preferences == null)
            return;

        foreach (var (slot, character) in _prefManager.Preferences.Characters)
        {
            var button = new LobbySavedShipsCharacterPickerButton(_entManager, _prototypes, character);
            var picked = slot;
            button.OnPressed += _ => OpenTransferConfirm(picked, character.Name);
            _characterButtons[slot] = button;
            Characters.AddChild(button);
        }
    }

    private int TransferTargets(int? owner)
    {
        var count = 0;
        foreach (var slot in _characterButtons.Keys)
        {
            if (slot != owner)
                count++;
        }

        return count;
    }

    private void RefreshCharacters()
    {
        var owner = _selectedBerth?.OccupantCharacterIndex;
        var active = _transferMode && _selectedBerth != null;

        foreach (var (slot, button) in _characterButtons)
        {
            button.Visible = _selectedBerth == null || slot != owner;
            button.Disabled = !active;
            button.Modulate = active ? Color.White : DrydockText.Disabled;
        }

        CharacterHeader.Modulate = active ? DrydockText.SelectedBorder : DrydockText.Dim;
        CharacterPanel.PanelOverride = active
            ? new StyleBoxFlat { BorderColor = DrydockText.SelectedBorder, BorderThickness = new Thickness(1) }
            : null;

        string hint;
        if (_selectedBerth == null)
            hint = Loc.GetString("shipyard-console-saved-ships-transfer-select-ship");
        else if (TransferTargets(owner) == 0)
            hint = Loc.GetString("shipyard-console-saved-ships-transfer-only-one");
        else if (!active)
            hint = Loc.GetString("shipyard-console-saved-ships-transfer-hint");
        else
            hint = Loc.GetString("shipyard-console-saved-ships-transfer-pick", ("ship", _selectedBerth.OccupantName ?? "?"));

        CharacterHint.Text = hint;
    }

    private void OpenTransferConfirm(int slot, string characterName)
    {
        if (!_transferMode || _selectedBerth?.OccupantShipId is not { } shipId)
            return;

        var shipName = _selectedBerth.OccupantName ?? "?";
        var prompt = new DrydockConfirmPrompt(
            Loc.GetString("shipyard-console-saved-ships-transfer-confirm-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-saved-ships-transfer-confirm-body", ("ship", shipName), ("character", characterName)),
            Loc.GetString("shipyard-console-saved-ships-transfer-confirm-button"),
            () =>
            {
                _transferMode = false;
                OnTransferShip?.Invoke(shipId, slot);
                PopulateBerthDetail();
                RefreshCharacters();
            });

        prompt.OpenCentered();
        _openWindows.Add(prompt);
    }


    private void TryExport(Guid shipId)
    {
        if (Exporting)
            return;

        _exportElapsed = 0f;
        _exportReplied = false;
        ExportStatusLabel.Visible = false;
        OnExportShip?.Invoke(shipId);
        PopulateBerthDetail();
    }

    public void ExportReplyArrived()
    {
        _exportReplied = true;
    }

    public void EndExport(bool? success)
    {
        _exportElapsed = null;
        _exportReplied = false;

        ExportStatusLabel.Visible = success != null;
        if (success is { } ok)
        {
            ExportStatusLabel.Text = Loc.GetString(ok ? "shipyard-console-export-done" : "shipyard-console-export-failed");
            ExportStatusLabel.Modulate = ok ? DrydockText.Dim : DrydockText.Warning;
        }

        PopulateBerthDetail();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_exportElapsed is not { } elapsed || _exportReplied)
            return;

        elapsed += args.DeltaSeconds;
        _exportElapsed = elapsed;

        if (elapsed >= ExportTimeoutSeconds)
            EndExport(false);
    }


    private void OpenDeletePrompt(Guid shipId, string shipName, int berthId)
    {
        var newPrompt = new DrydockTextPrompt(
            Loc.GetString("shipyard-console-delete-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-delete-body", ("ship", shipName), ("berth", berthId)),
            Loc.GetString("shipyard-console-sell-warning"),
            Loc.GetString("shipyard-console-sell-placeholder", ("ship", shipName)), // Uses the sell placeholders since they fit
            Loc.GetString("shipyard-console-delete-button"),
            typed => string.Equals(typed.Trim(), shipName, StringComparison.Ordinal),
            null,
            destructive: true,
            typed => OnDeleteShip?.Invoke(shipId, typed.Trim()));

        newPrompt.OpenCentered();
        _openWindows.Add(newPrompt);
    }

    private bool TryGetCharacterName(int? selectedIndex, out string charName)
    {
        charName = Loc.GetString("shipyard-console-saved-ships-unknown-character");
        if (_prefManager.Preferences == null || selectedIndex == null)
            return false;

        foreach (var (charIndex, character) in _prefManager.Preferences.Characters)
        {
            if (charIndex != selectedIndex)
                continue;

            charName = character.Name;
            return true;
        }

        return false;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _state.OnStateChanged -= OnStateChanged;

        foreach (var control in _openWindows)
            control.Close();
    }

    private void OnStateChanged(StateChangedEventArgs obj)
    {
        if (obj.NewState is not GameplayState)
            return;

        Close();
    }
}
