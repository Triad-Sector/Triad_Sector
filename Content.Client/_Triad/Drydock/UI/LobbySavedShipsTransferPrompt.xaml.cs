using Content.Client.Lobby;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Triad.Drydock.UI;

/// <summary>
/// The window for transferring your ships to another character slot
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbySavedShipsTransferPrompt : FancyWindow
{
    [Dependency] private IClientPreferencesManager _preferencesManager = default!;
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    public LobbySavedShipsTransferPrompt(string shipName, int? previousOwnerCharacter, Action<int> onSelect)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        if (!_preferencesManager.ServerDataLoaded)
            return;

        TransferHeader.Text = Loc.GetString("shipyard-console-transfer-owner-prompt-header", ("ship", shipName));

        foreach (var (slot, character) in _preferencesManager.Preferences!.Characters)
        {
            if (slot == previousOwnerCharacter)
                continue;

            var characterPickerButton = new LobbySavedShipsCharacterPickerButton(_entManager,
                _prototypes,
                character);

            Characters.AddChild(characterPickerButton);

            characterPickerButton.OnPressed += _ =>
            {
                onSelect?.Invoke(slot);
                Close();
            };
        }
    }
}
