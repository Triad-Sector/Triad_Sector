    /// <summary>
    /// Triad: Sell…, saying what the scrap pays against the hull's appraisal and which berth it
    /// frees, locked until the ship's exact name is typed. The server compares again.
    /// </summary>
    private void OpenSellPrompt(Guid shipId, string shipName, int price, int? appraisal, int berthId)
    {
        var basis = appraisal is > 0 ? appraisal.Value : price;
        var percent = basis > 0 ? (int)Math.Round(price * 100.0 / basis) : 100;

        new DrydockTextPrompt(
            Loc.GetString("shipyard-console-sell-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-sell-body",
                ("ship", shipName),
                ("price", BankSystemExtensions.ToSpesoString(price)),
                ("percent", percent),
                ("appraisal", BankSystemExtensions.ToSpesoString(basis)),
                ("berth", berthId)),
            Loc.GetString("shipyard-console-sell-warning"),
            Loc.GetString("shipyard-console-sell-placeholder", ("ship", shipName)),
            Loc.GetString("shipyard-console-sell-button"),
            typed => string.Equals(typed.Trim(), shipName, StringComparison.Ordinal),
            null,
            destructive: true,
            typed => OnSellStoredShip?.Invoke(shipId, typed.Trim())).OpenCentered();
    }

    /// <summary>
    /// Triad: one card per ship of the operator's in the impound lot, to the Impound artboard: the
    /// name, class and tag, then the reason it was taken and the fee on two labelled lines, and
    /// beside them Reclaim and Abandon… behind a name-typed prompt. Reclaim only arms the free
    /// berths below with Store reclaim, which is what spends the fee, and turns into Cancel until
    /// one is pressed. It greys on a fee the balance cannot cover or with no berth that fits, and a
    /// warning line says why. A locked card draws the reason, says an admin holds it, and offers
    /// neither, to the ImpoundLocked artboard.
    /// </summary>
    private void PopulateImpounds()
    {
        Impounds.RemoveAllChildren();

        foreach (var ship in _lastImpounded)
        {
            var (panel, line, text) = Card(ship.Redeemable ? DrydockText.ImpoundBorder : DrydockText.ImpoundLockedBorder, DrydockText.ImpoundFill);
            var headline = new FormattedMessage();
            headline.AddBoldSized(ship.Name, 14);
            headline.AddColored(" · " + DrydockText.Class(ship.SizeClass) + " · ", DrydockText.Dim);
            headline.AddColored(Loc.GetString("shipyard-console-impound-tag"), DrydockText.Impound);
            var headlineLabel = new RichTextLabel();
            headlineLabel.SetMessage(headline);
            text.AddChild(headlineLabel);

            // Two labelled lines under the headline, as the artboard draws them (user 2026-09-12):
            // the reason, in the body colour on a card the owner can act on and red on a locked
            // one, then the fee. The appraisal share and the no-deadline note are not drawn.
            if (!string.IsNullOrWhiteSpace(ship.Reason))
            {
                var markup = Loc.GetString("shipyard-console-impound-reason", ("reason", FormattedMessage.EscapeText(ship.Reason)));
                if (!ship.Redeemable)
                    markup = $"[color={DrydockText.ImpoundReason.ToHexNoAlpha()}]{markup}[/color]";
                var reason = new RichTextLabel();
                reason.SetMessage(FormattedMessage.FromMarkupPermissive(markup));
                text.AddChild(reason);
            }

            if (ship.Redeemable)
            {
                var fee = new RichTextLabel();
                fee.SetMessage(FormattedMessage.FromMarkupPermissive(ship.Fee > 0
                    ? Loc.GetString("shipyard-console-impound-fee", ("fee", BankSystemExtensions.ToSpesoString(ship.Fee)))
                    : Loc.GetString("shipyard-console-impound-fee-free")));
                text.AddChild(fee);

                // Only when it applies; the card carries no standing small print.
                var unaffordable = ship.Fee > _lastBalance;
                if (unaffordable)
                {
                    text.AddChild(new Label
                    {
                        Text = Loc.GetString("shipyard-console-impound-unaffordable-note", ("fee", BankSystemExtensions.ToSpesoString(ship.Fee))),
                        Modulate = DrydockText.Warning,
                    });
                }

                var noBerth = ship.FittingBerthIds.Count == 0;
                if (noBerth)
                {
                    text.AddChild(new Label
                    {
                        Text = Loc.GetString("shipyard-console-impound-no-fit-button"),
                        Modulate = DrydockText.Warning,
                    });
                }
                line.AddChild(text);

                // The buttons sit centred beside the four lines of text, as the artboard draws
                // them; a horizontal box stretches its children to the row's height unless told not to.
                var arming = _reclaiming?.ShipId == ship.ShipId;
                var reclaim = new Button
                {
                    Text = Loc.GetString(arming ? "shipyard-console-transfer-cancel-button" : "shipyard-console-impound-reclaim-button"),
                    StyleClasses = { "ButtonSquare" },
                    MinWidth = 96,
                    Margin = new Thickness(12, 0, 0, 0),
                    VerticalAlignment = VAlignment.Center,
                    Disabled = !_validId || noBerth || unaffordable,
                };
                var abandon = new Button
                {
                    Text = Loc.GetString("shipyard-console-impound-abandon-button"),
                    StyleClasses = { "ButtonSquare" },
                    MinWidth = 96,
                    Margin = new Thickness(8, 0, 0, 0),
                    VerticalAlignment = VAlignment.Center,
                    Disabled = !_validId,
                };
                line.AddChild(reclaim);
                line.AddChild(abandon);

                var shipId = ship.ShipId;
                var shipName = ship.Name;
                var reclaimed = ship;
                reclaim.OnPressed += _ => SetReclaiming(arming ? null : reclaimed);
                abandon.OnPressed += _ => OpenAbandonPrompt(shipId, shipName);
            }
            else
            {
                text.AddChild(new Label { Text = Loc.GetString("shipyard-console-impound-locked-note"), Modulate = DrydockText.Sub });
                line.AddChild(text);

                var pill = new PanelContainer
                {
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(12, 0, 0, 0),
                    PanelOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.FromHex("#1a1212"),
                        BorderColor = DrydockText.ImpoundLockedBorder,
                        BorderThickness = new Thickness(1),
                    },
                };
                pill.AddChild(new Label { Text = Loc.GetString("shipyard-console-impound-locked-pill"), Modulate = DrydockText.Impound, Margin = new Thickness(8, 2) });
                line.AddChild(pill);
            }

            Impounds.AddChild(panel);
        }
    }

    /// <summary>
    /// Triad: the card scaffold shared by an impound and a transfer alert - a bordered, filled
    /// panel holding a horizontal row, with the vertical text column the caller fills sitting
    /// alongside it. Only the border/fill colour is parameterised; the headline and everything
    /// past it is the caller's own, so it stays with them.
    /// </summary>
    private static (PanelContainer Panel, BoxContainer Line, BoxContainer Text) Card(Color borderColor, Color fillColor)
    {
        var panel = new PanelContainer
        {
            Margin = new Thickness(0, 0, 0, 10),
            PanelOverride = new StyleBoxFlat
            {
                BorderThickness = new Thickness(2),
                BorderColor = borderColor,
                BackgroundColor = fillColor,
            },
        };
        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(10, 6), VerticalAlignment = VAlignment.Center };
        panel.AddChild(line);

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };

        return (panel, line, text);
    }

    /// <summary>Triad: arms the free berths for a reclaim, or with null puts them back to Store.</summary>
    private void SetReclaiming(DrydockImpoundedShipInfo? ship)
    {
        _reclaiming = ship;
        PopulateImpounds();
        DrawStoreButtons();
    }

    private void OpenAbandonPrompt(Guid shipId, string shipName)
