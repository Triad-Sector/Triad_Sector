    /// <summary>
    /// Triad: the picker for Transfer…, filled from the captains the last state listed with how
    /// many free berths each has, greyed when none of them would take the ship. Offer commits.
    /// </summary>
    private void OpenTransferPicker(Guid shipId, string shipName, string? shipClass, int berthId)
    {
        var items = _lastCaptains
            .OrderBy(c => c.Name, StringComparer.CurrentCultureIgnoreCase)
            .Select(captain =>
            {
                var fits = captain.FreeBerthClasses.Any(berthClass => ShipSizeRules.Fits(shipClass, berthClass));
                var recipient = captain.UserId;
                return new DrydockMenuButton.Item(
                    captain.Name,
                    fits
                        ? Loc.GetString("shipyard-console-transfer-picker-berths", ("count", captain.FreeBerthClasses.Count))
                        : Loc.GetString("shipyard-console-transfer-picker-no-berth"),
                    fits,
                    () => OnOfferTransfer?.Invoke(shipId, recipient));
            })
            .ToList();

        new DrydockListPicker(
            Loc.GetString("shipyard-console-transfer-picker-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-transfer-picker-placeholder"),
            Loc.GetString("shipyard-console-transfer-picker-body", ("ship", shipName), ("berth", berthId), ("minutes", _offerMinutes)),
            Loc.GetString("shipyard-console-transfer-picker-button"),
            Loc.GetString("shipyard-console-transfer-picker-empty"),
            items).OpenCentered();
    }

