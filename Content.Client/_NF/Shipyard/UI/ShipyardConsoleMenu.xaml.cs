                {
                    text.AddChild(new Label
                    {
                        Text = Loc.GetString("shipyard-console-impound-unaffordable-note", ("fee", BankSystemExtensions.ToSpesoString(ship.Fee))),
                        Modulate = DrydockText.Warning,
                    });
                }
                line.AddChild(text);

                // The picker opens on the berth the server would choose and lists every free berth,
                // the ones too small greyed with the reason; picking only changes where Reclaim lands.
                var target = ship.DefaultBerthId;
                // The three buttons sit centred beside the four lines of text, as the artboard draws
                // them; a horizontal box stretches its children to the row's height unless told not to.
                var into = new DrydockMenuButton
                {
                    StyleClasses = { "ButtonSquare" },
                    MinWidth = 130,
                    AlignRight = true,
                    Margin = new Thickness(12, 0, 8, 0),
                    VerticalAlignment = VAlignment.Center,
                    Text = IntoText(target),
                };
                into.SetItems(BerthItems(_freeBerths, ship.FittingBerthIds, id =>
                {
                    target = id;
                    into.Text = IntoText(id);
                }));
                line.AddChild(into);

                var reclaim = new Button
                {
                    Text = Loc.GetString("shipyard-console-impound-reclaim-button"),
                    StyleClasses = { "ButtonSquare", StyleNano.ButtonPrimary },
                    MinWidth = 96,
                    VerticalAlignment = VAlignment.Center,
                    Disabled = !_validId || target == null || unaffordable,
                };
                var abandon = new Button
                {
                    Text = Loc.GetString("shipyard-console-impound-abandon-button"),
                    StyleClasses = { "ButtonSquare" },
                    MinWidth = 96,
                    Margin = new Thickness(8, 0, 0, 0),
                    VerticalAlignment = VAlignment.Center,
                    Disabled = !_validId,
                };
                line.AddChild(reclaim);
                line.AddChild(abandon);

                var shipId = ship.ShipId;
                var shipName = ship.Name;
                reclaim.OnPressed += _ =>
                {
                    if (target is { } berth)
                        OnRedeemImpound?.Invoke(shipId, berth);
                };
                abandon.OnPressed += _ => OpenAbandonPrompt(shipId, shipName);
            }
            else
            {
                text.AddChild(new Label { Text = Loc.GetString("shipyard-console-impound-locked-note"), Modulate = DrydockText.Sub });
                line.AddChild(text);

                var pill = new PanelContainer
                {
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(12, 0, 0, 0),
                    PanelOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.FromHex("#1a1212"),
                        BorderColor = DrydockText.ImpoundLockedBorder,
                        BorderThickness = new Thickness(1),
                    },
                };
                pill.AddChild(new Label { Text = Loc.GetString("shipyard-console-impound-locked-pill"), Modulate = DrydockText.Impound, Margin = new Thickness(8, 2) });
                line.AddChild(pill);
            }

            Impounds.AddChild(panel);
        }
    }

    /// <summary>
    /// Triad: the card scaffold shared by an impound and a transfer alert - a bordered, filled
    /// panel holding a horizontal row, with the vertical text column the caller fills sitting
    /// alongside it. Only the border/fill colour is parameterised; the headline and everything
    /// past it is the caller's own, so it stays with them.
    /// </summary>
    private static (PanelContainer Panel, BoxContainer Line, BoxContainer Text) Card(Color borderColor, Color fillColor)
    {
        var panel = new PanelContainer
        {
            Margin = new Thickness(0, 0, 0, 10),
            PanelOverride = new StyleBoxFlat
            {
                BorderThickness = new Thickness(2),
                BorderColor = borderColor,
                BackgroundColor = fillColor,
            },
        };
        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(10, 6), VerticalAlignment = VAlignment.Center };
        panel.AddChild(line);

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };

        return (panel, line, text);
    }

    private static string IntoText(int? berth)
    {
        return (berth is { } id
            ? Loc.GetString("shipyard-console-impound-into-button", ("berth", id))
            : Loc.GetString("shipyard-console-impound-no-fit-button")) + DrydockText.Caret;
    }

    /// <summary>
    /// Triad: Abandon…, the sale confirmation's shape with its own words: no figure is quoted,
    /// because abandoning pays nothing, and the ship's exact name unlocks the verb. The server
    /// compares again.
    /// </summary>
    private void OpenAbandonPrompt(Guid shipId, string shipName)
    {
        new DrydockTextPrompt(
            Loc.GetString("shipyard-console-abandon-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-abandon-body", ("ship", shipName)),
            Loc.GetString("shipyard-console-abandon-warning"),
            Loc.GetString("shipyard-console-abandon-placeholder", ("ship", shipName)),
            Loc.GetString("shipyard-console-abandon-button"),
            typed => string.Equals(typed.Trim(), shipName, StringComparison.Ordinal),
            null,
            destructive: true,
            typed => OnAbandonShip?.Invoke(shipId, typed.Trim())).OpenCentered();
    }

    /// <summary>
    /// Triad: one alert per offer addressed to the operator, drawn as a line in the escrow amber:
    /// who offers what and where it lands, the clock, Accept, Decline. The last-berth warning
    /// sits under the first line whenever taking the ship would leave one of the operator's own
    /// with nowhere to dock; Accept is disabled outright when no free berth fits.
    /// </summary>
    private void PopulateOffers()
    {
        Offers.RemoveAllChildren();

        foreach (var offer in _lastOffers)
        {
            var (panel, line, text) = Card(DrydockText.AmberBorder, DrydockText.AmberFill);
            var headline = new FormattedMessage();
            headline.AddBold(offer.OfferedBy);
            headline.AddColored(" " + Loc.GetString("shipyard-console-transfer-offers") + " ", DrydockText.Dim);
            headline.AddBold(offer.ShipName);
            headline.AddColored(" " + (offer.LandsInBerthId is { } berth
                ? Loc.GetString("shipyard-console-transfer-into", ("class", DrydockText.Class(offer.SizeClass)), ("berth", berth))
                : Loc.GetString("shipyard-console-transfer-no-room", ("class", DrydockText.Class(offer.SizeClass)))), DrydockText.Dim);
            var headlineLabel = new RichTextLabel();
            headlineLabel.SetMessage(headline);
            text.AddChild(headlineLabel);

            // Taking the offer uses one free berth; warn when that leaves fewer than the ships out.
            if (offer.LandsInBerthId != null && _shipsOut.Count > 0 && _freeBerths.Count - 1 < _shipsOut.Count)
            {
                var stranded = _lastDeedShip?.Name
                    ?? _shipsOut[0].Name
                    ?? Loc.GetString("shipyard-console-transfer-your-ship");
                text.AddChild(new Label
                {
                    Text = Loc.GetString("shipyard-console-transfer-warning", ("ship", stranded)),
                    Modulate = DrydockText.Warning,
                });
            }
            line.AddChild(text);

            var clock = new Label { Text = DrydockText.Left(offer.SecondsLeft), Modulate = DrydockText.Dim, Margin = new Thickness(12, 0) };
            line.AddChild(clock);
            _offerClocks.Add((clock, offer.SecondsLeft));

            var accept = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-accept-button"),
                StyleClasses = { "ButtonSquare", StyleNano.ButtonPrimary },
                MinWidth = 84,
                VerticalAlignment = VAlignment.Center,
                Disabled = !_validId || offer.LandsInBerthId == null,
            };
            var decline = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-decline-button"),
                StyleClasses = { "ButtonSquare" },
                MinWidth = 84,
                Margin = new Thickness(8, 0, 0, 0),
                VerticalAlignment = VAlignment.Center,
                Disabled = !_validId,
            };
            line.AddChild(accept);
            line.AddChild(decline);

            var transferId = offer.TransferId;
            accept.OnPressed += _ => OnAcceptTransfer?.Invoke(transferId);
            decline.OnPressed += _ => OnDeclineTransfer?.Invoke(transferId);

            Offers.AddChild(panel);
        }
    }
